// Regenerates js/catalog.js — the id/name lists the UI needs — from the real part definitions.
// The UI imports the catalog instead of the part modules so the main thread never loads the geometry engine.
//   node tools/gen-catalog.mjs        (tests/smoke.mjs fails if the file is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASES } from '../js/parts/bases.js';
import { COLUMNS } from '../js/parts/columns.js';
import { TOPPERS } from '../js/parts/toppers.js';
import { PLAQUES } from '../js/parts/plaques.js';
import { SHAPES } from '../js/parts/shapes.js';

export function catalogSource() {
  const j = (v) => JSON.stringify(v).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/,/g, ', ').replace(/\{/g, '{ ').replace(/\}/g, ' }');
  const list = (name, items) => `export const ${name} = [\n${items.map((i) => '  ' + j(i) + ',').join('\n')}\n];\n`;
  return `// AUTO-GENERATED by tools/gen-catalog.mjs — do not edit by hand.\n// ids and names of every part (\`rect\`: has a separate depth, \`solid\`: has geometry, \`custom\`: needs extra inputs).\n\n`
    + list('BASES', BASES.map((b) => ({ id: b.id, name: b.name, rect: !!b.rect })))
    + list('COLUMNS', COLUMNS.map((c) => ({ id: c.id, name: c.name, solid: !!c.build })))
    + list('TOPPERS', TOPPERS.map((t) => ({ id: t.id, name: t.name, solid: !!t.build, ...(t.custom ? { custom: t.custom } : {}) })))
    + list('PLAQUES', PLAQUES.map((p) => ({ id: p.id, name: p.name })))
    + list('SHAPES', SHAPES.map((p) => ({ id: p.id, name: p.name })));
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../js/catalog.js');
  fs.writeFileSync(out, catalogSource());
  console.log('wrote js/catalog.js');
}
